import 'package:drift/drift.dart';

/// Study themes (e.g. Java, Biology, History).
@DataClassName('ThemeRow')
class Themes extends Table {
  TextColumn get id => text()();
  TextColumn get name => text()();
  DateTimeColumn get createdAt => dateTime()();

  @override
  Set<Column> get primaryKey => {id};
}

/// Subtopics belonging to a theme (e.g. Collections, Genetics).
@DataClassName('SubtopicRow')
class Subtopics extends Table {
  TextColumn get id => text()();
  TextColumn get themeId => text().references(Themes, #id)();
  TextColumn get name => text()();
  DateTimeColumn get createdAt => dateTime()();

  @override
  Set<Column> get primaryKey => {id};
}

/// Multiple-choice questions.
///
/// The [promptVersion] and [generationMetadata] fields are filled when the
/// question is generated by AI (Stage 3); they stay null for example questions
/// created locally. The [contentType] field distinguishes text/code.
@DataClassName('QuestionRow')
class Questions extends Table {
  TextColumn get id => text()();
  // Logical reference to the subtopic (slug). Kept as a plain column, without
  // an enforced FK, to decouple the question from prior subtopic registration
  // in the MVP; the `theme`/`subtopic` fields below are the source for
  // filtering and display.
  TextColumn get subtopicId => text()();
  TextColumn get theme => text()();
  TextColumn get subtopic => text()();
  TextColumn get statement => text()();
  // Optional code snippet, rendered as a monospaced block below the statement.
  TextColumn get codeSnippet => text().nullable()();
  TextColumn get contentType => text().withDefault(const Constant('text'))();
  TextColumn get difficulty => text()();
  TextColumn get tags => text().withDefault(const Constant(''))();
  DateTimeColumn get createdAt => dateTime()();
  TextColumn get promptVersion => text().nullable()();
  TextColumn get generationMetadata => text().nullable()();

  @override
  Set<Column> get primaryKey => {id};
}

/// Answer options of a question. Each option keeps, in a stable way, its text,
/// individual explanation, correct flag and canonical order.
@DataClassName('AnswerOptionRow')
class AnswerOptions extends Table {
  // Option id, stable only WITHIN a question (e.g. 'a'..'d'). It is not
  // globally unique, so the primary key is the pair {questionId, id}.
  TextColumn get id => text()();
  TextColumn get questionId =>
      text().references(Questions, #id, onDelete: KeyAction.cascade)();
  // Named `optionText` (not `text`) to avoid colliding with drift's `text()`
  // column builder method.
  TextColumn get optionText => text()();
  TextColumn get explanation => text()();
  BoolColumn get correct => boolean()();
  TextColumn get contentType => text().withDefault(const Constant('text'))();
  IntColumn get position => integer()();

  // Composite key: option ids repeat across questions ('a','b','c','d'), so
  // uniqueness is per-question. Using only `id` as the key caused later
  // questions' options to be dropped by insertOrIgnore due to id collisions.
  @override
  Set<Column> get primaryKey => {questionId, id};
}

